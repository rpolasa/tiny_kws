#!/usr/bin/env python3
"""Generate the C headers for kws_pico from the tiny_kws submission repo.

    python tools/gen_headers.py --repo D:/MY/asic/tapeouts/TTsky26e/tiny_kws

Writes src/gen/:
  kws_model_blob.h   model.bin as a byte array + class names        (live run)
  kws_golden_m1.h    golden features -> logits/top1/top2/detect      (M1: GRU + detector)
  kws_golden_m2.h    golden PCM -> features                         (M2: front end)
  kws_golden_m3.h    golden PDM bits -> CIC samples -> features     (M3: PDM path)

Everything expected here comes from the repo's own golden model (test/golden.py, which wraps
model/kws_fe.c and model/gru_int.py) - the same reference the cocotb tests check the RTL against.
Needs: numpy, scipy, and gcc on PATH (golden.py builds kws_fe.c as a shared library), so run it on
Linux / WSL / MSYS2. The generated headers are committed, so this is only needed after a model change.
"""
import argparse, hashlib, os, sys
import numpy as np

CLASSES = ["_silence_", "_unknown_", "yes", "no", "up", "down", "left", "right", "on", "off", "stop", "go"]
HOP = 512
THR, NDET, NFILL = 12, 4, 2          # detector settings used for the expected DETECT flags (chip defaults)
M2_CLIPS = 4                          # PCM clips in the M2 header (each 1 s = 16000 samples)
M3_CLIP = 2                           # clip used for the PDM test (same clip as cocotb test_06)


def carr(ctype, name, vals, per_line=16, fmt="{}"):
    vals = list(vals)
    lines = []
    for i in range(0, len(vals), per_line):
        lines.append("    " + ",".join(fmt.format(int(v)) for v in vals[i:i + per_line]) + ",")
    return f"static const {ctype} {name}[{len(vals)}] = {{\n" + "\n".join(lines) + "\n};\n"


def header(guard, body, src):
    return (f"/* generated by tools/gen_headers.py from {src} - do not edit */\n"
            f"#ifndef {guard}\n#define {guard}\n#include <stdint.h>\n\n{body}\n#endif\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True, help="path of the tiny_kws submission repo")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "gen"))
    a = ap.parse_args()
    sys.path.insert(0, os.path.join(a.repo, "test"))
    import golden  # noqa: E402  (also puts model/ on sys.path)
    import gru_int  # noqa: E402

    os.makedirs(a.out, exist_ok=True)
    blob = open(golden.MODEL_BIN, "rb").read()
    H, C = blob[7], blob[1]
    assert blob[0] == 0xA5 and C == len(CLASSES), "model header / class list mismatch"
    md5 = hashlib.md5(blob).hexdigest()
    _, ig = golden.load_model(H)
    pcm, y = golden.vectors()
    src = f"model.bin md5 {md5}"

    # ---- model blob
    body = (f"#define KWS_MODEL_MD5 \"{md5}\"\n#define KWS_MODEL_BYTES {len(blob)}\n"
            f"#define KWS_NUM_CLASSES {C}\n"
            "static const char *const KWS_CLASS_NAMES[KWS_NUM_CLASSES] = {"
            + ",".join(f"\"{c}\"" for c in CLASSES) + "};\n"
            + carr("uint8_t", "KWS_MODEL_BLOB", blob, 24, "0x{:02x}"))
    open(os.path.join(a.out, "kws_model_blob.h"), "w").write(header("KWS_MODEL_BLOB_H", body, src))

    # ---- M1: features -> GRU/FC -> top1/top2 -> detector  (all clips)
    nclip = pcm.shape[0]
    feats = [golden.fe_pcm(pcm[i], HOP) for i in range(nclip)]
    T = feats[0].shape[0]
    F, LG, TOP, DET = [], [], [], []
    for f in feats:
        h = ig.init_state(1)
        tops = []
        for t in range(T):
            h, lg = ig.step(f[t:t + 1].astype(np.int64), h)
            LG += [int(v) for v in lg[0]]
            tops.append(gru_int.top2(lg[0]))
        TOP += [v for tp in tops for v in tp]
        DET += [int(d) for d in golden.detect_seq(tops, NFILL, THR, NDET)]
        F += [int(v) for v in f.reshape(-1)]
    body = (f"#define M1_CLIPS {nclip}\n#define M1_FRAMES {T}\n#define M1_THR {THR}\n#define M1_N {NDET}\n"
            f"#define M1_NFILL {NFILL}\n"
            + carr("int8_t", "M1_LABEL", y) + carr("uint8_t", "M1_FEAT", F)
            + carr("int8_t", "M1_LOGIT", LG, C) + carr("int8_t", "M1_TOP", TOP, 24)
            + carr("uint8_t", "M1_DET", DET, 31))
    open(os.path.join(a.out, "kws_golden_m1.h"), "w").write(header("KWS_GOLDEN_M1_H", body, src))

    # ---- M2: PCM -> features (fresh front-end state per clip)
    P2 = [int(v) for i in range(M2_CLIPS) for v in pcm[i]]
    F2 = [int(v) for i in range(M2_CLIPS) for v in feats[i].reshape(-1)]
    body = (f"#define M2_CLIPS {M2_CLIPS}\n#define M2_SAMPLES {pcm.shape[1]}\n#define M2_FRAMES {T}\n"
            + carr("int16_t", "M2_PCM", P2) + carr("uint8_t", "M2_FEAT", F2))
    open(os.path.join(a.out, "kws_golden_m2.h"), "w").write(header("KWS_GOLDEN_M2_H", body, src))

    # ---- M3: PDM bits (sigma-delta mic model) -> CIC3 -> PCM -> features
    bits = golden.pdm_modulate(pcm[M3_CLIP], 64)          # 64 bits per 16 kHz sample
    f3, cic = golden.fe_pdm(bits.astype(np.uint8), HOP)
    assert len(bits) % 32 == 0
    # pack 32 bits per word, first bit in the MSB = the PIO 'in' order (shift left, autopush 32)
    words = np.packbits(bits.reshape(-1, 32), axis=1, bitorder="big").view(">u4").reshape(-1)
    body = (f"#define M3_CLIP {M3_CLIP}\n#define M3_WORDS {len(words)}\n#define M3_SAMPLES {len(cic)}\n"
            f"#define M3_FRAMES {f3.shape[0]}\n"
            + carr("uint32_t", "M3_PDM", words, 8, "0x{:08x}u") + carr("int16_t", "M3_CIC", cic)
            + carr("uint8_t", "M3_FEAT", f3.reshape(-1)))
    open(os.path.join(a.out, "kws_golden_m3.h"), "w").write(header("KWS_GOLDEN_M3_H", body, src))
    print(f"model {md5} H={H} C={C}; M1 {nclip}x{T} frames, {sum(DET)} detections; "
          f"M2 {M2_CLIPS} clips; M3 {len(words)} words -> {len(cic)} samples, {f3.shape[0]} frames")


if __name__ == "__main__":
    main()
